/* Social icons — Framer renders these as a solid-color div masked by an SVG.
   Mask files extracted verbatim to public/images/icons/. */

const SOCIAL_MASKS = {
  dribbble: "/images/icons/dribbble.svg",
  twitter: "/images/icons/twitter.svg",
  instagram: "/images/icons/instagram.svg",
  youtube: "/images/icons/youtube.svg",
} as const;

export function SocialGlyph({
  name,
  className,
}: {
  name: keyof typeof SOCIAL_MASKS;
  className?: string;
}) {
  const url = `url("${SOCIAL_MASKS[name]}")`;
  return (
    <div
      aria-hidden
      className={cn("icon-mask size-6", className)}
      style={{ maskImage: url, WebkitMaskImage: url }}
    />
  );
}
